typedef unsigned int u32;
typedef unsigned char u8;
_Static_assert(sizeof(u32)==4,"word size");
typedef struct { u32 words[16]; } EarlyHeader;
typedef struct { u32 sequence,tick,source_kind,context_id,arg0,arg1; } EarlyEvent;
typedef struct { EarlyHeader header; EarlyEvent entries[32]; } EarlyStore;
typedef struct { u8 view_control[128],unit_rows_t[512],settings_uid[128]; } DiagBoot;
typedef struct { u32 words[16]; } AutoPermit;
typedef struct { u8 bytes[128]; } AutoTransaction;
_Static_assert(sizeof(EarlyHeader)==64,"early header");
_Static_assert(sizeof(EarlyEvent)==24,"early entry");
_Static_assert(sizeof(EarlyStore)==832,"early store");
_Static_assert(sizeof(DiagBoot)==768,"diagnostic storage");
_Static_assert(sizeof(AutoPermit)==64,"permit");
_Static_assert(sizeof(AutoTransaction)==128,"transaction");
