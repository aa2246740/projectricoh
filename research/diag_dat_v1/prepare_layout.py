"""Generate the fixed load allowlist and the eight-column page map."""
from pathlib import Path
import json
import sys
sys.path.insert(0, str(Path(__file__).resolve().parent))
from scope import *

SPEC = ROOT / 'research/body_v4_storage/validation/diagnostic_spec.json'
EXTRA = {
    'resident_state': ['0x20054705', 1],
    'resident_inflight': ['0x20054706', 1],
    'resident_flags': ['0x200547d4', 4],
    'resident_check': ['0x20054798', 4],
    'resident_fault': ['0x2005475c', 4],
    'resident_early': ['0x200547e8', 4],
    'rpc_ready': ['0x200d7fd8', 4],
    'unit_ready': ['0x2040f804', 4],
}
PAGES = {
    'A': [['fc38'], ['c1a8'], ['c19c'], ['c560'], ['c1bc','c208','t8state'],
          ['t8event','t8flags','t8opcode'], ['pause']],
    'B': [['t6wait'], ['t6timer'], ['t8wait'], ['t8timer'], ['t28wait'], ['t28timer'], ['t8context']],
    'C': [['mode'], ['usbui0'], ['usbui1'], ['divertcb'], ['t28context'],
          ['t28opcode','divert','cardmirror'], ['error','selectedvolume','selectedfile']],
    'D': [['high'], ['cache0mode','cache0q'], ['cache0pos'], ['cache1mode','cache1q'], ['cache1pos'],
          ['slot0a','slot0b','slot0mode'], ['slot1a','slot1b','slot1mode']],
    'F': [['resident_state','resident_inflight','open_high'], ['resident_flags'], ['resident_check'],
          ['resident_fault'], ['resident_early'], ['rpc_ready'], ['unit_ready']],
}


def main():
    spec = json.loads(SPEC.read_text())
    fields = dict(spec['fields'], **EXTRA)
    assert len(fields) == 50
    ids = {key:i for i,key in enumerate(fields)}
    used = [f for rows in PAGES.values() for row in rows for f in row if f != 'open_high']
    assert len(used) == len(set(used)) == len(fields) and set(used) == set(fields)
    for key, (at, width) in fields.items():
        assert width in (1,2,4) and int(at,16) % width == 0 and 0x20000000 <= int(at,16) < 0x20600000
    text = ['/* Generated by research/diag_dat_v1/prepare_layout.py. */',
            '#ifndef DIAG_FIELDS_H', '#define DIAG_FIELDS_H',
            'typedef struct { uint32_t address; uint8_t bytes; } DiagField;',
            'typedef struct { uint8_t field,digits; } DiagCell;',
            'enum { DIAG_FIELDS=50, DIAG_OPEN_HIGH=255 };',
            'static const DiagField diag_fields[DIAG_FIELDS]={']
    text += [f'    {{{at}u,{width}}}, /* {key} */' for key,(at,width) in fields.items()]
    text += ['};', 'static const DiagCell diag_layout[5][7][4]={']
    for page, rows in PAGES.items():
        assert len(rows) == 7
        text += [f'  {{ /* {page} */']
        for row in rows:
            cells = [(255,4) if f == 'open_high' else (ids[f],2*fields[f][1]) for f in row]
            assert 1 <= len(cells) <= 4 and sum(w for _,w in cells) <= 8
            cells += [(0,0)]*(4-len(cells))
            text += ['    {' + ','.join('{%d,%d}' % cell for cell in cells) + '},']
        text += ['  },']
    text += ['};',
        '_Static_assert(offsetof(RvRoot,state)==5 && offsetof(RvRoot,inflight)==6 &&',
        ' offsetof(RvRoot,flags)==212 && offsetof(RvRoot,fault)==92 &&',
        ' offsetof(RvRoot,check_failure)==152 && offsetof(RvRoot,diag_early)==232,"resident field map");',
        '#endif', '']
    (ENGINE / 'candidate/containers/product/diag_fields.h').write_text('\n'.join(text))
    save(OUT / 'layout.json', dict(fields=fields, field_order=list(fields), pages=PAGES, rows=8, columns=8,
        header='{page}{open_low16:04X} {quality}', quality=dict(S='SAME',C='CHANGE',U='unavailable'),
        sampling='two complete reads, show second, once per delivered H01 menu_open', generation=125))
    print('PASS layout: 50 fixed fields, 5 pages, each 8 rows and at most 8 ASCII characters')


if __name__ == '__main__':
    main()
