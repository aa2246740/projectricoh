"""Behavioral negative cases for the frozen quality gate, no solver mutation."""
import copy
import json
from pathlib import Path
import sys
sys.dont_write_bytecode = True
sys.path.insert(0, str(Path(__file__).resolve().parent))
import isolated as iso

rt = iso.rt
np = rt.np
gate = iso.gate_module()


def main():
    folder = rt.ROOT / "artifacts/downloads/fit-fast-r1/round2/quality/full-guard-final"
    rows = rt.read(folder / "per_photo.json")
    pairs = [(row["reference"], row["actual"]) for row in rows]
    assert gate.aggregate(pairs)[0]
    cases = []
    for index in (30, 38, 46):
        trials = []
        chosen_rows = [r for r in rows if r["index"] == index and r["key"] == "L1"]
        assert len(chosen_rows) == 17 and all(r["reference"][0] is None for r in chosen_rows)
        for amount in (.5, .1, .01, .001, .0001, .00001, .000001):
            changed, selected = [], []
            for row in rows:
                before, after = row["reference"], list(row["actual"])
                if row["index"] == index and row["key"] == "L1":
                    after = [None, *[v+amount for v in after[1:]]]
                    selected.append((before, after))
                changed.append((before, after))
            aggregate_passed, totals = gate.aggregate(changed)
            trials.append(dict(increase=amount, aggregate_passed=aggregate_passed))
            if aggregate_passed:
                break
        old = gate.median([a[0] for a, b in selected])
        new = gate.median([b[0] for a, b in selected])
        delta = None if old is None else new-old
        # Same predicates as quality_gate.py:263-264 and 313-315.
        per_fit_passed = delta is None or delta >= -1.-gate.rounding_tolerance(old, new)
        selected_passed = delta is None or delta >= -.1-gate.rounding_tolerance(old, new)
        old_de = gate.median([a[1] for a, b in selected])
        new_de = gate.median([b[1] for a, b in selected])
        assert new_de > old_de
        row = dict(case="undefined-target-"+str(index), changed_photo_rows=len(selected),
                   reference_photo_median_de00=old_de, actual_photo_median_de00=new_de,
                   median_de00_increase=new_de-old_de,
                   uniform_addition=amount, attempted_additions=trials,
                   per_fit_passed=per_fit_passed,
                   selected_and_L1_passed=selected_passed,
                   aggregate_passed=aggregate_passed, aggregate=totals,
                   fixture_change=False, training_change=False,
                   interpretation="Actual table with a uniform score increase in one None target's L1. A score-table negative case, not a solver-output claim")
        cases.append(row)
        assert per_fit_passed and selected_passed and aggregate_passed, row
    # A new target can have a large absolute regression while staying below
    # every global quantile. This synthetic fixture proves the missing rule
    # without claiming those values were generated by the reviewed solver.
    synthetic = [((80., 5., 10., 20.), (80., 5., 10., 20.)) for _ in range(1000)]
    synthetic += [((None, .1, .2, .3), (None, .6, .7, .8)) for _ in range(17)]
    synthetic_passed, synthetic_totals = gate.aggregate(synthetic)
    assert synthetic_passed
    # The fixed 17-photo assumption makes the gate inapplicable to recipe-redo's
    # new domain rather than validating it. This failure is explicit.
    doc = dict(scores={"a12-50": None, "a12-28": None, "mount-a12": None})
    try:
        gate.photo_scores(doc)
    except AssertionError as exc:
        empty_photos = dict(rejected=True, error=str(exc))
    else:
        raise AssertionError("No-photo case was unexpectedly accepted")
    # Gate policy is hash-bound, but its numeric constants are in the code.
    # Record only demonstrated behavior here; do not rewrite that policy.
    result = dict(none_cases=cases,
                  synthetic_none_case=dict(changed_photos=17, median_de00_increase=.5,
                      aggregate_passed=synthetic_passed, aggregate=synthetic_totals,
                      interpretation="Synthetic scores, not actual fitted output"),
                  fixed_photo_scope=empty_photos,
                  source_sha256=iso.sha(Path(gate.__file__)), nice=rt.os.getpriority(rt.os.PRIO_PROCESS, 0))
    iso.write("gate_negative_cases.json", result)
    print(json.dumps(dict(none_hidden_regressions=len(cases),
                          photo_scope_rejected=empty_photos["rejected"],
                          source_sha256=result["source_sha256"])), flush=True)


if __name__ == "__main__":
    main()
