"""Export the one calibrated integer contract to JSON and a standalone C header."""
import sys
from pathlib import Path
sys.path.insert(0, str(Path(__file__).resolve().parent))
import json
import support as s

PARAMS = ('amount', 'contrast', 'highlight', 'shadow', 'fade', 'saturation', 'warmth', 'tint', 'split', 'filter')
LABELS = ('Amt', 'Cont', 'High', 'Shad', 'Fade', 'Sat', 'Warm', 'Tint', 'Split', 'Filt')


def build():
    groups = json.loads((s.LOCAL / 'calibration.json').read_text())['groups']
    units = list(dict.fromkeys(g['unit'] for g in groups))
    controls = [dict(id=i, name=p, label=LABELS[i], dose_index=i-1)
                for i, p in enumerate(PARAMS)]
    items, recipes = [], []
    for unit_index, unit in enumerate(units):
        for slot in range(1, 9):
            selected = [g for g in groups if g['unit'] == unit and g['slot'] == slot]
            recipes.append(dict(unit=unit_index, slot=slot, first_item=len(items), item_count=len(selected)))
            for g in selected:
                points = [dict(level=int(level), dose=dose) for level, dose in g['doses'].items()]
                items.append(dict(control=PARAMS.index(g['param']), point_count=len(points),
                                  min_level=points[0]['level'], max_level=points[-1]['level'],
                                  default_level=100 if g['param'] == 'amount' else 0,
                                  cap_lower=g['cap_lower'], cap_upper=g['cap_upper'],
                                  amount_step=g['amount_step'], points=points))
    return dict(schema='knobs-v2-r2/engine-integers/1', q=4096, max_points=19,
                wb_method=0, split_method=1, units=units, controls=controls, recipes=recipes, items=items)


def render(data):
    lines = ['/* Generated by src/export_tables.py. Contains derived integer doses only. */',
             '#ifndef KNOBS_V2_R2_TABLES_H', '#define KNOBS_V2_R2_TABLES_H', '#include <stdint.h>',
             '#define KV2_SCHEMA "knobs-v2-r2/engine-integers/1"',
             '#define KV2_Q 4096', '#define KV2_MAX_POINTS 19',
             f'#define KV2_UNIT_COUNT {len(data["units"])}',
             f'#define KV2_RECIPE_COUNT {len(data["recipes"])}',
             f'#define KV2_ITEM_COUNT {len(data["items"])}',
             '#define KV2_CONTROL_COUNT 10', '#define KV2_WB_METHOD 0', '#define KV2_SPLIT_METHOD 1',
             'typedef struct { int16_t level, dose; } Kv2Point;',
             'typedef struct { int16_t control, point_count, min_level, max_level, default_level;',
             '                 int16_t cap_lower, cap_upper, amount_step; Kv2Point points[KV2_MAX_POINTS]; } Kv2Item;',
             'typedef struct { int16_t unit, slot, first_item, item_count; } Kv2Recipe;',
             'typedef struct { const char *name, *label; int16_t dose_index; } Kv2Control;',
             'static const char kv2_units[KV2_UNIT_COUNT][8] = {' + ','.join('"'+u+'"' for u in data['units']) + '};',
             'static const Kv2Control kv2_controls[KV2_CONTROL_COUNT] = {']
    for c in data['controls']:
        lines.append('    {"%s","%s",%d},' % (c['name'], c['label'], c['dose_index']))
    lines.append('};\nstatic const Kv2Recipe kv2_recipes[KV2_RECIPE_COUNT] = {')
    for r in data['recipes']:
        lines.append('    {%d,%d,%d,%d},' % (r['unit'], r['slot'], r['first_item'], r['item_count']))
    lines.append('};\nstatic const Kv2Item kv2_items[KV2_ITEM_COUNT] = {')
    fields = ('control', 'point_count', 'min_level', 'max_level', 'default_level', 'cap_lower', 'cap_upper', 'amount_step')
    for item in data['items']:
        prefix = ','.join(str(item[f]) for f in fields)
        points = ','.join('{%d,%d}' % (p['level'], p['dose']) for p in item['points'])
        lines.append('    {' + prefix + ',{' + points + '}},')
    lines += ['};', '#endif', '']
    return '\n'.join(lines)


def main():
    s.guard()
    data = build()
    s.dump(s.HERE / 'tables/final.json', data)
    (s.HERE / 'tables/knobs_v2_r2_tables.h').write_text(render(data))
    print('exported', len(data['recipes']), 'recipes', len(data['items']), 'menu items')


if __name__ == '__main__':
    main()
