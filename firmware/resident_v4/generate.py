"""Generate the v4 ABI from layout.json. Writes only this resident directory."""
from pathlib import Path
import hashlib
import json

HERE = Path(__file__).resolve().parent


def generate():
    s = json.loads((HERE / 'layout.json').read_text())
    assert s['root_address'] == 0x20054600
    assert s['payload_address'] == 0x2005276c
    assert s['payload_limit'] == 0x20054538
    lines = ['/* Generated by generate.py; edit layout.json instead. */',
             '#ifndef RV4_ABI_H', '#define RV4_ABI_H',
             '#include <stdint.h>', '#include <stddef.h>']
    for k, v in [('MAJOR', s['major']), ('MINOR', s['minor']),
                 ('SCHEMA', s['dispatch_schema']), ('CPU_ID', s['cpu_id']),
                 ('FIRMWARE_REVISION', s['firmware_revision']), ('MAX_ROWS', s['max_rows']),
                 ('ROOT_ADDRESS', s['root_address']), ('PAYLOAD_ADDRESS', s['payload_address']),
                 ('PAYLOAD_LIMIT', s['payload_limit'])]:
        lines.append(f'#define RV4_{k} {v}u')
    for k, v in s['limits'].items():
        lines.append(f'#define RV4_MAX_{k.upper()} {v}u')
    for key, prefix, start, bits in [('entries', 'ENTRY', 0, False),
                                    ('capabilities', 'CAP', 0, True),
                                    ('services', 'SERVICE', 1, False),
                                    ('epochs', 'E', 0, False),
                                    ('contexts', 'CONTEXT', 1, False),
                                    ('actions', 'ACTION', 0, False)]:
        lines.append('enum { ' + ', '.join(
            f'RV4_{prefix}_{n}=' + (f'(1u<<{i})' if bits else str(i))
            for i, n in enumerate(s[key], start)) + ' };')
    lines.append('enum { '+', '.join(f'RV4_{n}={v}' for n,v in s['statuses'].items())+' };')
    for service,operations in s['operations'].items():
        for name,value in operations.items():
            lines.append(f'#define RV4_OP_{service}_{name} {value}u')
    lines += ['#define RV4_HEADER_BYTES 256u', '#define RV4_ENTRY_COUNT 16u',
              '#define RV4_KNOWN_EVENTS 0x00000fffu',
              '#define RV4_KNOWN_SERVICES 0x000000ffu',
              '#define RV4_IMPLEMENTED_CAPS (RV4_CAP_QUERY|RV4_CAP_UI_PUBLISH|RV4_CAP_UI_HINT)',
              '#define RV4_REQUIRED_ENTRIES (1u<<RV4_ENTRY_INIT)']
    for n, off, shape in s['root']:
        if isinstance(shape, list):
            lines.append('typedef struct { uint32_t ' + ','.join(shape) + '; } Rv4' + n.title() + ';')
    lines.append('typedef struct {')
    for n, off, shape in s['root']:
        lines.append('    ' + (f'Rv4{n.title()} {n};' if isinstance(shape, list)
                              else f'uint32_t {n}[{shape}];'))
    lines.append('} Rv4Root;')
    for n, off, shape in s['root']:
        lines.append(f'_Static_assert(offsetof(Rv4Root,{n})=={off},"root {n}");')
    lines.append('_Static_assert(sizeof(Rv4Root)==512,"root bytes");')
    lines += [
        'typedef struct {',
        ' uint8_t magic[8]; uint16_t major,minor,header_bytes,dispatch_count;',
        ' uint32_t file_bytes,header_crc,payload_crc,generation;',
        ' uint16_t firmware,cpu; uint8_t official[32],build[32],abi[16];',
        ' uint32_t bss_bytes,code_offset,code_bytes,reloc_offset,reloc_count;',
        ' uint32_t capabilities_low,capabilities_high,schema,required_events,host_minor,reserved0;',
        ' uint32_t entries[16]; uint16_t service_major,service_minor;',
        ' uint32_t required_services; uint8_t reserved[24];',
        '} Rv4Envelope;',
        'typedef struct { uint16_t version,bytes,event,phase; uint32_t flags,session_token,session_generation,view_generation,job_capture_id,owner_context,native_event,native_caller,args[6]; } Rv4Event;',
        'typedef struct { uint16_t version,bytes; int32_t status; uint32_t action,actual,token,observed_generation,diagnostic,detail; } Rv4Reply;',
        'typedef struct { uint16_t major,minor,header_bytes,descriptor_bytes; uint32_t total_bytes,service_count,capabilities_low,capabilities_high,host_call,session_token; } Rv4HostApi;',
        'typedef struct { uint16_t id,major,minor,bytes; uint32_t operations,contexts; } Rv4ServiceDescriptor;',
        'typedef int32_t (*Rv4Entry)(const Rv4HostApi *,uint32_t,const Rv4Event *,Rv4Reply *);',
        'typedef int32_t (*Rv4HostCall)(uint32_t,uint32_t,const Rv4Event *,Rv4Reply *);',
        '_Static_assert(sizeof(Rv4Envelope)==256,"envelope");',
        '_Static_assert(sizeof(Rv4Event)==64,"event");',
        '_Static_assert(sizeof(Rv4Reply)==32,"reply");',
        '_Static_assert(sizeof(Rv4HostApi)==32,"api header");',
        '_Static_assert(sizeof(Rv4ServiceDescriptor)==16,"service");']
    fields = {'file_bytes':16, 'official':36, 'build':68, 'abi':100, 'bss_bytes':116,
              'code_offset':120, 'reloc_offset':128, 'capabilities_low':136,
              'schema':144, 'entries':160, 'service_major':224, 'reserved':232}
    for n, off in fields.items():
        lines.append(f'_Static_assert(offsetof(Rv4Envelope,{n})=={off},"wire {n}");')
    lines += ['#endif', '']
    out = HERE / 'generated'
    out.mkdir(exist_ok=True)
    header = '\n'.join(lines)
    (out / 'abi.h').write_text(header)
    abi = hashlib.sha256((HERE/'layout.json').read_bytes()+header.encode()+(HERE/'resident.h').read_bytes()).digest()[:16]
    (out / 'abi-id.json').write_text(json.dumps({'abi_id':abi.hex()}, indent=2)+'\n')
    return s


if __name__ == '__main__':
    generate()
