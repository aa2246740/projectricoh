"""Host model of the gen 148 transforms and the generated C tables.

The 17^3 table, the coordinate table and the input words come from cp_vectors.py (a byte-identical copy of
firmware/lut_p0_timing/vectors.py). The grain/vignette transform here is the reference of cp_grain in probe.c.
"""
import struct
import zlib

import cp_vectors as v

PAIRS = 1024
GRAIN_SEED = 0x12345678


def gain_table():
    """Q8 vignette gain over 256 positions, 255 in the middle and 191 at both ends."""
    return [255 - ((i - 128) * (i - 128) * 64) // 16384 for i in range(256)]


def inputs():
    return [v.input_word(i) for i in range(PAIRS)]


def lut_output(words):
    nodes, coord = v.table(), v.coordinates()
    return b''.join(v.transform(w, nodes, coord) for w in words)


def grain_output(words, seed=GRAIN_SEED):
    gain, x, out = gain_table(), seed, []
    for i, w in enumerate(words):
        g = gain[i & 255]
        x = (x * 1664525 + 1013904223) & 0xffffffff
        a = (((w >> 24) * g) >> 8) + ((x >> 27) & 31) - 16
        b = ((((w >> 16) & 255) * g) >> 8) + ((x >> 19) & 31) - 16
        a, b = min(255, max(0, a)), min(255, max(0, b))
        out.append(struct.pack('>I', (a << 24) | (b << 16) | (w & 0xffff)))
    return b''.join(out)


def crcs():
    words = inputs()
    return zlib.crc32(lut_output(words)), zlib.crc32(grain_output(words))


def c_source():
    lut_crc, grain_crc = crcs()
    nodes, coord = v.table(), v.coordinates()
    code = '#include "kernel.h"\n/* Generated by firmware/engine_cpuprobe_v38/cp_model.py. */\n'
    code += 'const uint16_t p0_table[P0_NODES*3]={\n' + ','.join(str(x) for x in nodes) + '};\n'
    code += 'const uint32_t p0_coord[256]={' + ','.join(str(x) + 'u' for x in coord) + '};\n'
    code += 'const uint8_t cp_gain[256]={' + ','.join(str(x) for x in gain_table()) + '};\n'
    code += 'const uint32_t cp_lut_crc=%du,cp_grain_crc=%du,cp_grain_seed=%du;\n' % (lut_crc, grain_crc, GRAIN_SEED)
    code += 'uint32_t p0_input(uint32_t i){ static const uint32_t s[]={' + ','.join(hex(x) + 'u' for x in v.SPECIAL) + '};uint32_t x;\n'
    code += 'if(i<sizeof(s)/sizeof(s[0])){return s[i];}\nif(i<128){x=(i>>3)&255u;return (x<<24)|(x<<16)|(128u<<8)|128u;}\n'
    code += 'x=i*0x9e3779b9u+0x7f4a7c15u;x^=x>>16;x*=0x85ebca6bu;x^=x>>13;return x;}\n'
    return code
